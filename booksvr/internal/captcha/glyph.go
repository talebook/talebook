// drawGlyph 把字符按点阵放大绘制到 (x, y)，size 为期望高度（像素）。
//
// 未知字符画一个实心方块，保证不会静默丢失。
func drawGlyph(img *image.RGBA, ch rune, x, y, size int, c color.RGBA) {
	rows, ok := glyphs[ch]
	if !ok {
		drawBlock(img, x, y, size*3/5, size, c)
		return
	}
	// 每个点阵像素放大为 scale x scale 的方块。
	scale := size / glyphHeight
	if scale < 1 {
		scale = 1
	}
	for ry := 0; ry < glyphHeight; ry++ {
		bits := rows[ry]
		for rx := 0; rx < glyphWidth; rx++ {
			if bits&(1<<uint(glyphWidth-1-rx)) == 0 {
				continue
			}
			px := x + rx*scale
			py := y + ry*scale
			for dy := 0; dy < scale; dy++ {
				for dx := 0; dx < scale; dx++ {
					pt := image.Pt(px+dx, py+dy)
					if pt.In(img.Bounds()) {
						img.Set(pt.X, pt.Y, c)
					}
				}
			}
		}
	}
}

// drawBlock 画一个实心矩形（未知字符的兜底）。
func drawBlock(img *image.RGBA, x, y, w, h int, c color.RGBA) {
	for dy := 0; dy < h; dy++ {
		for dx := 0; dx < w; dx++ {
			pt := image.Pt(x+dx, y+dy)
			if pt.In(img.Bounds()) {
				img.Set(pt.X, pt.Y, c)
			}
		}
	}
}
